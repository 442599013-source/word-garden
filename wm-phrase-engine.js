const tileKey = word => word.toLowerCase().replace(/’/g, "'").replace(/^[“"()]+|[.,!?;:()“”"]+$/g,'');
function naturalTiles(tokens) {
 const words = tokens.map(token => ({en:tileKey(token), pause:/[.,!?;:—–]$/.test(token.replace(/[”")]+$/g,''))}));
 const groups = new Map();
 const occupied = new Set();
 // Claim known three-word expressions first so a shorter match cannot split them.
 for(const size of [3,2]){
  for(let start=0;start+size<=words.length;start++){
   const indices=Array.from({length:size},(_,i)=>start+i);
   if(indices.some(i=>occupied.has(i)||(i<start+size-1&&words[i].pause)))continue;
   const meaning=collocations.get(indices.map(i=>words[i].en).join(' '));
   if(!meaning)continue;
   groups.set(start,{size,meaning});
   indices.forEach(i=>occupied.add(i));
  }
 }
 const tiles=[];
 for(let start=0;start<words.length;){
  const group=groups.get(start);
  const end=start+(group?.size||1);
  tiles.push({en:tokens.slice(start,end).map(cleanToken).join(' '),cn:group?.meaning||''});
  start=end;
 }
 return tiles;
}
function cleanToken(word){return word.replace(/^[“"(]+|[.,!?;:)”"]+$/g,'')}
function migrateWordPosition(tiles,oldPosition){
 let count=0;
 return tiles.findIndex(tile=>{count+=tile.en.split(' ').length;return count>oldPosition});
}
